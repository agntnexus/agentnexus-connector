"""Check that the release builder refuses every release it must not produce.

`scripts/build_release.py` is the one path in this repository that holds a private signing key, so
what it refuses matters more than what it does. Each case below violates one protected condition
and requires a refusal:

* a signing key inside this repository, or inside any other Git work tree;
* a wheel whose updater still carries the placeholders, or carries a different key;
* a wheel, a manifest or a package whose versions disagree;
* a `SOURCE_DATE_EPOCH` that is not the committer time of the revision being built, a dirty tree,
  and two builds of one revision that do not come out byte-identical;
* a release tree that lost, gained or altered a file, re-signed an older manifest with another key,
  or points an artifact away from the origin the loaders accept;
* private key material anywhere in the output, including inside the wheel.

The last group builds a real release end to end in a throwaway clone and then reproduces it from
the recorded source commit with no private key at all, which is the property a stranger relies on.

Every key here is an ephemeral P-256 key generated by the test and written only under pytest's
temporary directory. None of them is a release key, and none of them signs anything published.
"""

from __future__ import annotations

import hashlib
import importlib.util
import io
import json
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path
from types import ModuleType

import pytest
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
BUILDER = REPOSITORY_ROOT / "scripts" / "build_release.py"


def load_builder() -> ModuleType:
    """Import the builder from its path; it is a script, not a package module."""
    spec = importlib.util.spec_from_file_location("build_release", BUILDER)
    assert spec is not None and spec.loader is not None, f"{BUILDER} cannot be loaded"
    module = importlib.util.module_from_spec(spec)
    sys.modules["build_release"] = module
    spec.loader.exec_module(module)
    return module


builder = load_builder()


def write_key(directory: Path) -> tuple[Path, ec.EllipticCurvePrivateKey]:
    """Write a throwaway P-256 key under `directory` and return it with its path."""
    key = ec.generate_private_key(ec.SECP256R1())
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / "throwaway-release-signing.pem"
    path.write_bytes(
        key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )
    )
    return path, key


def git(repository: Path, *arguments: str) -> str:
    """Run git in `repository` and return its output."""
    completed = subprocess.run(  # noqa: S603 - fixed argument list, no shell.
        ["git", "-C", str(repository), *arguments],  # noqa: S607 - git from PATH.
        capture_output=True,
        encoding="utf-8",
        check=True,
    )
    return completed.stdout.strip()


# --- where the key may live --------------------------------------------------------------------


def test_refuses_a_key_inside_this_repository(tmp_path: Path) -> None:
    """Refuse a key inside this repository before it is read."""
    inside = REPOSITORY_ROOT / "connector-release" / "never-a-key.pem"
    with pytest.raises(builder.ReleaseBuildError, match="inside a Git work tree"):
        builder.refuse_key_location(inside, repository=REPOSITORY_ROOT)


def test_refuses_a_key_inside_any_other_git_work_tree(tmp_path: Path) -> None:
    """Refuse a key inside any Git work tree, not only inside this one."""
    other = tmp_path / "some-other-repository"
    (other / ".git").mkdir(parents=True)
    with pytest.raises(builder.ReleaseBuildError, match="inside a Git work tree"):
        builder.refuse_key_location(other / "keys" / "release.pem", repository=REPOSITORY_ROOT)


def test_accepts_a_key_outside_every_work_tree(tmp_path: Path) -> None:
    """Accept a key outside every work tree, so the refusals above are specific."""
    path, _ = write_key(tmp_path / "custody")
    assert builder.refuse_key_location(path, repository=REPOSITORY_ROOT) == path.resolve()


def test_refuses_a_key_that_is_not_p256(tmp_path: Path) -> None:
    """Refuse any curve but P-256, the only one the loaders verify."""
    other = ec.generate_private_key(ec.SECP384R1())
    path = tmp_path / "custody" / "wrong-curve.pem"
    path.parent.mkdir()
    path.write_bytes(
        other.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )
    )
    with pytest.raises(builder.ReleaseBuildError, match="P-256"):
        builder.load_signing_key(path, repository=REPOSITORY_ROOT)


