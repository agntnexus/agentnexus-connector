"""Check that the release builder refuses every release it must not produce.

`scripts/build_release.py` is the one path in this repository that holds a private signing key, so
what it refuses matters more than what it does. Each case below violates one protected condition
and requires a refusal:

* a signing key inside this repository, or inside any other Git work tree;
* a wheel whose updater still carries the placeholders, or carries a different key;
* a wheel, a manifest or a package whose versions disagree;
* a `SOURCE_DATE_EPOCH` that is not the committer time of the revision being built, a dirty tree,
  and two builds of one revision that do not come out byte-identical;
* a release tree that lost, gained or altered a file, re-signed an older manifest with another key,
  or points an artifact away from the origin the loaders accept;
* private key material anywhere in the output, including inside the wheel;
* a release state that names a release other than the one the committed tree holds, or lets a
  candidate that is only built pass for the one the origin serves.

The end-to-end group builds a real release in a throwaway clone and then reproduces it from
the recorded source commit with no private key at all, which is the property a stranger relies on.

Every key here is an ephemeral P-256 key generated by the test and written only under pytest's
temporary directory. None of them is a release key, and none of them signs anything published.
"""

from __future__ import annotations

import hashlib
import importlib.util
import io
import json
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path
from types import ModuleType

import pytest
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
BUILDER = REPOSITORY_ROOT / "scripts" / "build_release.py"


def load_builder() -> ModuleType:
    """Import the builder from its path; it is a script, not a package module."""
    spec = importlib.util.spec_from_file_location("build_release", BUILDER)
    assert spec is not None and spec.loader is not None, f"{BUILDER} cannot be loaded"
    module = importlib.util.module_from_spec(spec)
    sys.modules["build_release"] = module
    spec.loader.exec_module(module)
    return module


builder = load_builder()


def write_key(directory: Path) -> tuple[Path, ec.EllipticCurvePrivateKey]:
    """Write a throwaway P-256 key under `directory` and return it with its path."""
    key = ec.generate_private_key(ec.SECP256R1())
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / "throwaway-release-signing.pem"
    path.write_bytes(
        key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )
    )
    return path, key


def git(repository: Path, *arguments: str) -> str:
    """Run git in `repository` and return its output."""
    completed = subprocess.run(  # noqa: S603 - fixed argument list, no shell.
        ["git", "-C", str(repository), *arguments],  # noqa: S607 - git from PATH.
        capture_output=True,
        encoding="utf-8",
        check=True,
    )
    return completed.stdout.strip()


# --- where the key may live --------------------------------------------------------------------


def test_refuses_a_key_inside_this_repository(tmp_path: Path) -> None:
    """Refuse a key inside this repository before it is read."""
    inside = REPOSITORY_ROOT / "connector-release" / "never-a-key.pem"
    with pytest.raises(builder.ReleaseBuildError, match="inside a Git work tree"):
        builder.refuse_key_location(inside, repository=REPOSITORY_ROOT)


def test_refuses_a_key_inside_any_other_git_work_tree(tmp_path: Path) -> None:
    """Refuse a key inside any Git work tree, not only inside this one."""
    other = tmp_path / "some-other-repository"
    (other / ".git").mkdir(parents=True)
    with pytest.raises(builder.ReleaseBuildError, match="inside a Git work tree"):
        builder.refuse_key_location(other / "keys" / "release.pem", repository=REPOSITORY_ROOT)


def test_accepts_a_key_outside_every_work_tree(tmp_path: Path) -> None:
    """Accept a key outside every work tree, so the refusals above are specific."""
    path, _ = write_key(tmp_path / "custody")
    assert builder.refuse_key_location(path, repository=REPOSITORY_ROOT) == path.resolve()


def test_refuses_a_key_that_is_not_p256(tmp_path: Path) -> None:
    """Refuse any curve but P-256, the only one the loaders verify."""
    other = ec.generate_private_key(ec.SECP384R1())
    path = tmp_path / "custody" / "wrong-curve.pem"
    path.parent.mkdir()
    path.write_bytes(
        other.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )
    )
    with pytest.raises(builder.ReleaseBuildError, match="P-256"):
        builder.load_signing_key(path, repository=REPOSITORY_ROOT)


# --- the wheel ---------------------------------------------------------------------------------


def fake_wheel(directory: Path, version: str, updater: str, metadata_version: str | None = None):
    """Write a minimal wheel carrying an updater and a METADATA."""
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"agentnexus_sdk-{version}-py3-none-any.whl"
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("agentnexus_sdk/updater.py", updater)
        archive.writestr(
            f"agentnexus_sdk-{version}.dist-info/METADATA",
            "Metadata-Version: 2.4\nName: agentnexus-sdk\n"
            f"Version: {metadata_version or version}\n",
        )
    return path


def test_refuses_an_unstamped_updater(tmp_path: Path) -> None:
    """Refuse an updater still carrying the placeholders; it could verify nothing."""
    updater = (
        'X: Final = "REPLACE_RELEASE_PUBLIC_KEY_X"\nY: Final = "REPLACE_RELEASE_PUBLIC_KEY_Y"\n'
    )
    wheel = fake_wheel(tmp_path, "9.9.9", updater)
    with pytest.raises(builder.ReleaseBuildError, match="unstamped updater"):
        builder.verify_wheel(wheel, version="9.9.9", coordinates=("a" * 64, "b" * 64))


def test_refuses_an_updater_stamped_with_another_key(tmp_path: Path) -> None:
    """Refuse an updater stamped with another key; it would trust the wrong releases."""
    wheel = fake_wheel(tmp_path, "9.9.9", f'X = "{"c" * 64}"\nY = "{"d" * 64}"\n')
    with pytest.raises(builder.ReleaseBuildError, match="different key"):
        builder.verify_wheel(wheel, version="9.9.9", coordinates=("a" * 64, "b" * 64))


def test_refuses_a_wheel_named_for_another_version(tmp_path: Path) -> None:
    """Refuse a wheel whose filename names another version."""
    wheel = fake_wheel(tmp_path, "9.9.8", f'X = "{"a" * 64}"\nY = "{"b" * 64}"\n')
    with pytest.raises(builder.ReleaseBuildError, match="does not carry version"):
        builder.verify_wheel(wheel, version="9.9.9", coordinates=("a" * 64, "b" * 64))


def test_refuses_wheel_metadata_for_another_version(tmp_path: Path) -> None:
    """Refuse a wheel whose own METADATA declares another version."""
    wheel = fake_wheel(tmp_path, "9.9.9", f'X = "{"a" * 64}"\nY = "{"b" * 64}"\n', "9.9.8")
    with pytest.raises(builder.ReleaseBuildError, match="METADATA"):
        builder.verify_wheel(wheel, version="9.9.9", coordinates=("a" * 64, "b" * 64))


def test_accepts_a_wheel_stamped_with_this_key(tmp_path: Path) -> None:
    """Accept a correctly stamped wheel, so the refusals above are specific."""
    wheel = fake_wheel(tmp_path, "9.9.9", f'X = "{"a" * 64}"\nY = "{"b" * 64}"\n')
    builder.verify_wheel(wheel, version="9.9.9", coordinates=("a" * 64, "b" * 64))


def test_refuses_package_versions_that_disagree(tmp_path: Path) -> None:
    """Refuse pyproject.toml and version.py naming two versions."""
    source = tmp_path / "source"
    (source / "src" / "agentnexus_sdk").mkdir(parents=True)
    (source / "pyproject.toml").write_text('[project]\nversion = "0.6.3"\n', encoding="utf-8")
    (source / "src" / "agentnexus_sdk" / "version.py").write_text(
        '__version__: Final = "0.6.2"\n', encoding="utf-8"
    )
    with pytest.raises(builder.ReleaseBuildError, match="disagree"):
        builder.read_version(source)


def test_refuses_a_version_other_than_the_one_expected(tmp_path: Path) -> None:
    """Refuse a commit that builds a version other than the one the operator named."""
    source = tmp_path / "source"
    (source / "src" / "agentnexus_sdk").mkdir(parents=True)
    (source / "pyproject.toml").write_text('[project]\nversion = "0.6.3"\n', encoding="utf-8")
    (source / "src" / "agentnexus_sdk" / "version.py").write_text(
        '__version__: Final = "0.6.3"\n', encoding="utf-8"
    )
    assert builder.read_version(source) == "0.6.3"
    with pytest.raises(builder.ReleaseBuildError, match=r"expected 0\.6\.4"):
        builder.read_version(source, expected="0.6.4")


