def test_the_epoch_is_the_committer_time_of_the_revision() -> None:
    """Derive the epoch from the commit, which is what lets anybody rederive it."""
    head = git(REPOSITORY_ROOT, "rev-parse", "HEAD")
    expected = int(git(REPOSITORY_ROOT, "log", "-1", "--format=%ct", head))
    assert builder.resolve_epoch(REPOSITORY_ROOT, head, environ={}) == expected


def test_refuses_an_inherited_epoch_that_is_not_the_revision(tmp_path: Path) -> None:
    """Refuse an exported epoch that disagrees with the commit instead of replacing it."""
    head = git(REPOSITORY_ROOT, "rev-parse", "HEAD")
    expected = int(git(REPOSITORY_ROOT, "log", "-1", "--format=%ct", head))
    with pytest.raises(builder.ReleaseBuildError, match="SOURCE_DATE_EPOCH"):
        builder.resolve_epoch(
            REPOSITORY_ROOT, head, environ={"SOURCE_DATE_EPOCH": str(expected + 1)}
        )


def test_refuses_two_builds_that_differ() -> None:
    """Refuse two different builds of one commit as not reproducible."""
    with pytest.raises(builder.ReleaseBuildError, match="not reproducible"):
        builder.require_reproducible(b"PK first", b"PK second")


def test_normalising_a_wheel_removes_what_the_platform_wrote(tmp_path: Path) -> None:
    """Drop the file mode and made-by system a platform wrote into the zip."""

    def written(system: int, mode: int) -> bytes:
        """Write one wheel variant, normalise it and return its bytes."""
        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
            info = zipfile.ZipInfo("agentnexus_sdk/__init__.py", date_time=(2026, 9, 23, 15, 0, 0))
            info.create_system = system
            info.external_attr = mode << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, b"print('same bytes')\n")
        path = tmp_path / f"{system}-{mode:o}.whl"
        path.write_bytes(buffer.getvalue())
        builder.normalise_wheel(path)
        return path.read_bytes()

    assert written(0, 0o100666) == written(3, 0o100644)


def test_normalising_a_wheel_removes_the_line_endings_windows_wrote(tmp_path: Path) -> None:
    """Fold the CRLF a Windows build writes into METADATA, and the RECORD line that pins it.

    Setuptools writes METADATA in text mode, so a Windows build carries CRLF there and only
    there. The RECORD that pins it has to follow, or the wheel no longer verifies on install.
    """

    def written(newline: bytes) -> bytes:
        """Write one wheel variant, normalise it and return its bytes."""
        metadata = newline.join([b"Metadata-Version: 2.4", b"Name: agentnexus-sdk", b""])
        digest = builder.record_digest(metadata)
        record = (
            f"agentnexus_sdk-9.9.9.dist-info/METADATA,{digest},{len(metadata)}\n"
            "agentnexus_sdk-9.9.9.dist-info/RECORD,,\n"
        ).encode()
        path = tmp_path / f"{len(newline)}.whl"
        with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
            archive.writestr("agentnexus_sdk-9.9.9.dist-info/METADATA", metadata)
            archive.writestr("agentnexus_sdk-9.9.9.dist-info/RECORD", record)
        builder.normalise_wheel(path)
        return path.read_bytes()

    normalised = written(b"\r\n")
    assert normalised == written(b"\n")
    with zipfile.ZipFile(io.BytesIO(normalised)) as archive:
        metadata = archive.read("agentnexus_sdk-9.9.9.dist-info/METADATA")
        record = archive.read("agentnexus_sdk-9.9.9.dist-info/RECORD").decode()
    assert b"\r" not in metadata
    assert builder.record_digest(metadata) in record


def test_refuses_a_dirty_tree(tmp_path: Path) -> None:
    """Refuse a tree with an untracked file; it is not its commit."""
    clone = tmp_path / "clone"
    git(tmp_path, "clone", "--quiet", "--no-hardlinks", str(REPOSITORY_ROOT), str(clone))
    (clone / "untracked.txt").write_text("not committed\n", encoding="utf-8")
    with pytest.raises(builder.ReleaseBuildError, match="uncommitted or untracked"):
        builder.require_clean_tree(clone)


# --- the release tree --------------------------------------------------------------------------


def test_private_material_is_found_in_a_file_and_inside_the_wheel(tmp_path: Path) -> None:
    """Find the private scalar in a file and key armour inside a wheel entry."""
    _, key = write_key(tmp_path / "custody")
    markers = builder.private_markers(key)
    tree = tmp_path / "tree"
    tree.mkdir()
    (tree / "notes.txt").write_text("nothing here\n", encoding="utf-8")
    assert builder.scan_private_material(tree, markers) == []

    scalar = format(key.private_numbers().private_value, "064x")
    (tree / "leak.txt").write_text(f"d={scalar}\n", encoding="utf-8")
    # Assembled at run time, so the tree-wide credential grep in CI does not find it here.
    armour = "-----BEGIN " + "PRIVATE KEY-----\n"
    with zipfile.ZipFile(tree / "leak.whl", "w") as archive:
        archive.writestr("agentnexus_sdk/leak.py", armour)
    found = builder.scan_private_material(tree, markers)
    assert any("leak.txt" in item for item in found)
    assert any("leak.whl" in item and "leak.py" in item for item in found)


