def fake_wheel(directory: Path, version: str, updater: str, metadata_version: str | None = None):
    """Write a minimal wheel carrying an updater and a METADATA."""
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"agentnexus_sdk-{version}-py3-none-any.whl"
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("agentnexus_sdk/updater.py", updater)
        archive.writestr(
            f"agentnexus_sdk-{version}.dist-info/METADATA",
            "Metadata-Version: 2.4\nName: agentnexus-sdk\n"
            f"Version: {metadata_version or version}\n",
        )
    return path


def test_refuses_an_unstamped_updater(tmp_path: Path) -> None:
    """Refuse an updater still carrying the placeholders; it could verify nothing."""
    updater = (
        'X: Final = "REPLACE_RELEASE_PUBLIC_KEY_X"\nY: Final = "REPLACE_RELEASE_PUBLIC_KEY_Y"\n'
    )
    wheel = fake_wheel(tmp_path, "9.9.9", updater)
    with pytest.raises(builder.ReleaseBuildError, match="unstamped updater"):
        builder.verify_wheel(wheel, version="9.9.9", coordinates=("a" * 64, "b" * 64))


def test_refuses_an_updater_stamped_with_another_key(tmp_path: Path) -> None:
    """Refuse an updater stamped with another key; it would trust the wrong releases."""
    wheel = fake_wheel(tmp_path, "9.9.9", f'X = "{"c" * 64}"\nY = "{"d" * 64}"\n')
    with pytest.raises(builder.ReleaseBuildError, match="different key"):
        builder.verify_wheel(wheel, version="9.9.9", coordinates=("a" * 64, "b" * 64))


def test_refuses_a_wheel_named_for_another_version(tmp_path: Path) -> None:
    """Refuse a wheel whose filename names another version."""
    wheel = fake_wheel(tmp_path, "9.9.8", f'X = "{"a" * 64}"\nY = "{"b" * 64}"\n')
    with pytest.raises(builder.ReleaseBuildError, match="does not carry version"):
        builder.verify_wheel(wheel, version="9.9.9", coordinates=("a" * 64, "b" * 64))


def test_refuses_wheel_metadata_for_another_version(tmp_path: Path) -> None:
    """Refuse a wheel whose own METADATA declares another version."""
    wheel = fake_wheel(tmp_path, "9.9.9", f'X = "{"a" * 64}"\nY = "{"b" * 64}"\n', "9.9.8")
    with pytest.raises(builder.ReleaseBuildError, match="METADATA"):
        builder.verify_wheel(wheel, version="9.9.9", coordinates=("a" * 64, "b" * 64))


def test_accepts_a_wheel_stamped_with_this_key(tmp_path: Path) -> None:
    """Accept a correctly stamped wheel, so the refusals above are specific."""
    wheel = fake_wheel(tmp_path, "9.9.9", f'X = "{"a" * 64}"\nY = "{"b" * 64}"\n')
    builder.verify_wheel(wheel, version="9.9.9", coordinates=("a" * 64, "b" * 64))


def test_refuses_package_versions_that_disagree(tmp_path: Path) -> None:
    """Refuse pyproject.toml and version.py naming two versions."""
    source = tmp_path / "source"
    (source / "src" / "agentnexus_sdk").mkdir(parents=True)
    (source / "pyproject.toml").write_text('[project]\nversion = "0.6.3"\n', encoding="utf-8")
    (source / "src" / "agentnexus_sdk" / "version.py").write_text(
        '__version__: Final = "0.6.2"\n', encoding="utf-8"
    )
    with pytest.raises(builder.ReleaseBuildError, match="disagree"):
        builder.read_version(source)


def test_refuses_a_version_other_than_the_one_expected(tmp_path: Path) -> None:
    """Refuse a commit that builds a version other than the one the operator named."""
    source = tmp_path / "source"
    (source / "src" / "agentnexus_sdk").mkdir(parents=True)
    (source / "pyproject.toml").write_text('[project]\nversion = "0.6.3"\n', encoding="utf-8")
    (source / "src" / "agentnexus_sdk" / "version.py").write_text(
        '__version__: Final = "0.6.3"\n', encoding="utf-8"
    )
    assert builder.read_version(source) == "0.6.3"
    with pytest.raises(builder.ReleaseBuildError, match=r"expected 0\.6\.4"):
        builder.read_version(source, expected="0.6.4")


