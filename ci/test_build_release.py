@pytest.mark.parametrize(
    "mutation",
    [
        "drop-a-loader",
        "drop-an-older-wheel",
        "alter-an-older-wheel",
        "add-a-stray-file",
        "change-a-loader-line",
        "move-the-artifact-off-origin",
        "resign-with-another-key",
        "plant-a-private-key",
    ],
)
def test_a_damaged_release_tree_is_refused(
    released: dict[str, object], tmp_path: Path, mutation: str
) -> None:
    """Refuse each damage to a release tree on its own."""
    clone = committed(released)
    version = str(released["version"])
    tree = tmp_path / "tree"
    shutil.copytree(clone / "connector-release", tree)
    previous = tmp_path / "previous"
    builder.export_commit(clone, str(released["source_commit"]), previous)
    key = released["key"]
    assert isinstance(key, ec.EllipticCurvePrivateKey)

    older = sorted((tree / "connector").glob("0.1.0/*.whl"))[0]
    manifest_path = tree / "connector" / "connector-release.json"
    if mutation == "drop-a-loader":
        (tree / "remove.ps1").unlink()
    elif mutation == "drop-an-older-wheel":
        older.unlink()
    elif mutation == "alter-an-older-wheel":
        older.write_bytes(older.read_bytes() + b"\0")
    elif mutation == "add-a-stray-file":
        (tree / "connector" / "notes.txt").write_text("stray\n", encoding="utf-8")
    elif mutation == "change-a-loader-line":
        loader = tree / "connect.sh"
        loader.write_text(loader.read_text(encoding="utf-8") + "echo extra\n", encoding="utf-8")
    elif mutation == "move-the-artifact-off-origin":
        document = json.loads(manifest_path.read_bytes())
        document["artifacts"][0]["url"] = document["artifacts"][0]["url"].replace(
            "https://agntnexus.com", "https://example.invalid"
        )
        manifest_path.write_bytes(builder.canonical_bytes(document))
        (tree / "connector" / "connector-release.json.sig").write_text(
            builder.sign(key, manifest_path.read_bytes()).hex(), encoding="ascii"
        )
    elif mutation == "resign-with-another-key":
        other = ec.generate_private_key(ec.SECP256R1())
        ox, oy = builder.public_coordinates(other)
        for name in builder.LOADERS:
            source = (previous / "installers" / name).read_text(encoding="utf-8")
            stamped = source.replace(builder.PLACEHOLDER_X, ox).replace(builder.PLACEHOLDER_Y, oy)
            (tree / name).write_bytes(stamped.encode("utf-8"))
        (tree / "connector" / "connector-release.json.sig").write_text(
            builder.sign(other, manifest_path.read_bytes()).hex(), encoding="ascii"
        )
    elif mutation == "plant-a-private-key":
        (tree / "connector" / version / "release-signing.pem").write_bytes(
            key.private_bytes(
                serialization.Encoding.PEM,
                serialization.PrivateFormat.PKCS8,
                serialization.NoEncryption(),
            )
        )

    failures = builder.check_release_tree(
        tree,
        previous=previous / "connector-release",
        installers=previous / "installers",
        version=version,
        markers=builder.private_markers(key),
    )
    assert failures, f"{mutation} was not refused"


def test_reproduction_refuses_a_wheel_that_is_not_the_source(
    released: dict[str, object],
) -> None:
    """Refuse a committed wheel its source does not build; restoring it passes again."""
    clone = committed(released)
    version = str(released["version"])
    wheel = clone / "connector-release" / "connector" / version
    target = wheel / f"agentnexus_sdk-{version}-py3-none-any.whl"
    original = target.read_bytes()
    try:
        builder.normalise_wheel(target, extra={"agentnexus_sdk/extra.py": b"x = 1\n"})
        git(clone, "commit", "--quiet", "-am", "test: a wheel nobody built from source")
        assert builder.main(["reproduce", "--repository", str(clone)]) == 1
    finally:
        target.write_bytes(original)
        git(clone, "commit", "--quiet", "-am", "test: restore the built wheel")
    assert builder.main(["reproduce", "--repository", str(clone)]) == 0


def test_reproduction_refuses_a_version_with_no_recorded_source(tmp_path: Path) -> None:
    """Refuse to reproduce a post-legacy version with no recorded source commit."""
    clone = tmp_path / "clone"
    git(tmp_path, "clone", "--quiet", "--no-hardlinks", str(REPOSITORY_ROOT), str(clone))
    state_path = clone / builder.STATE_FILE
    state = json.loads(state_path.read_text(encoding="utf-8"))
    manifest = json.loads(
        (clone / "connector-release" / "connector" / "connector-release.json").read_bytes()
    )
    version = manifest["connector_version"]
    state.get("reproducible_releases", {}).pop(version, None)
    state_path.write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")
    if version in builder.LEGACY_RELEASES:
        assert builder.main(["reproduce", "--repository", str(clone)]) == 0
        manifest["connector_version"] = "9.9.9"
        path = clone / "connector-release" / "connector" / "connector-release.json"
        path.write_bytes(builder.canonical_bytes(manifest))
    assert builder.main(["reproduce", "--repository", str(clone)]) == 1


