def test_a_build_never_moves_the_published_version(released: dict[str, object]) -> None:
    """A build records where its release came from; it never claims the origin serves it.

    The state the builder leaves behind still names the release served before, so the tree it
    wrote is refused until the operator declares the new release pending, and accepted then.
    """
    clone = released["clone"]
    assert isinstance(clone, Path)
    # The clone was made from this repository's HEAD, so that is the state before the build.
    before = json.loads(git(REPOSITORY_ROOT, "show", f"HEAD:{builder.STATE_FILE.as_posix()}"))
    state = json.loads((clone / builder.STATE_FILE).read_text(encoding="utf-8"))
    assert state["published_version"] == before["published_version"]
    tree, installers = clone / "connector-release", clone / "installers"
    assert published_state_failures(state, tree=tree, installers=installers)
    state["pending_version"] = released["version"]
    assert published_state_failures(state, tree=tree, installers=installers) == []
